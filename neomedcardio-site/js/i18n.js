/* joriy til: localStorage'da saqlanadi, standart — uz */
function nmcGetLang() {
  return localStorage.getItem("nmc_lang") || "uz";
}

function nmcSetLang(lang) {
  localStorage.setItem("nmc_lang", lang);
  nmcApplyLang(lang);
}

function nmcApplyLang(lang) {
  const dict = NMC_DICT[lang] || NMC_DICT.uz;
  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key] !== undefined) el.setAttribute("aria-label", dict[key]);
  });

  /* shifokor lavozimlari kabi alohida elementlar (data-role-uz / data-role-ru) */
  document.querySelectorAll("[data-role-uz]").forEach((el) => {
    const val = lang === "ru" ? el.getAttribute("data-role-ru") : el.getAttribute("data-role-uz");
    if (val) el.textContent = val;
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  nmcApplyLang(nmcGetLang());
});
